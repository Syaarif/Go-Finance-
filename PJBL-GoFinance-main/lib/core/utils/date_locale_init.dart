/// Inisialisasi data format tanggal khusus locale Indonesia (`id` / `id_ID` / `in`)
/// dan Inggris (`en_US` / `en_ISO`) tanpa membundel 120+ bahasa lain dari
/// `package:intl/date_symbol_data_local.dart`.
Future<void> initializeIndonesianDateFormatting() async {
  initializeDateSymbols(_minimalDateSymbolMap);
  initializeDatePatterns(_minimalDatePatternMap);
}

